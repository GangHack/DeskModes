    '_plural' = {
        param([int]$n)
        $ten = $n % 10
        $hundred = $n % 100
        if ($ten -eq 1 -and $hundred -ne 11) { return 0 }
        if ($ten -ge 2 -and $ten -le 4 -and ($hundred -lt 12 -or $hundred -gt 14)) { return 1 }
        return 2
    }

